"""PROTOTYPE (#236): tables from evidence/<major>/, the committed summaries and the manifest of raw files kept out of git.

Writes evidence/RESULTS.md, evidence/<major>/exp4-*.summary.json and EXCLUDED.sha256.
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
EV = HERE / 'evidence'
KEEP = ('summary.json', '.summary.json', 'RESULTS.md')


def load(path):
    return json.loads(path.read_text())


def row(*cells):
    return '| ' + ' | '.join(str(c) for c in cells) + ' |'


def main():
    out = ['# Results', '', 'Generated by `summarize.py` from the raw records under `evidence/`.', '']
    majors = sorted(p.name for p in EV.iterdir() if p.is_dir())

    out += ['## Experiment 1: feed order', '',
            row('Major', 'Run', 'Committed', 'Missed', 'Duplicated', 'Foreign', 'Reader restarted',
                'Tries mean / max', 'Delay p50 / p99 / max (s)', 'Wall (s)',
                'Committed/s', 'Behind schedule p50 / p99 / max (s)'),
            row(*['---'] * 12)]
    for m in majors:
        for run in ('stream-100k', 'seq-100k', 'control-100k', 'stream-12ps', 'seq-12ps', 'seq-12ps-short'):
            s = load(EV / m / ('exp1-' + run) / 'summary.json')
            assert not s['errors'] and s['db_matches_writers'], (m, run)
            out.append(row(s['version'], run, s['committed'], s['missed'], s['duplicated'], s['foreign_in_db'],
                           s['restarted'], '%s / %s' % (s['tries_mean'], s['tries_max']),
                           '%s / %s / %s' % (s['delay_p50'], s['delay_p99'], s['delay_max']), s['wall_seconds'],
                           *((s['events_per_second'], '%s / %s / %s' % (s['behind_schedule_p50'], s['behind_schedule_p99'], s['behind_schedule_max']))
                             if s['rate_per_writer'] else ('-', '-'))))

    out += ['', '## Experiment 2: dispatcher claim', '',
            row('Major', 'Dispatchers', 'Workflows', 'All dispatched', 'Start duplicates', 'Crashed claims (re-claimed after s)',
                'In-flight peak (budget 20)', 'Overshoot', 'Allowed'),
            row(*['---'] * 9)]
    for m in majors:
        for d in (2, 4):
            s = load(EV / m / ('exp2-d%d' % d) / 'summary.json')
            out.append(row(s['version'], d, s['workflows'], s['all_dispatched'], s['start_duplicates'],
                           ', '.join('%s (%s)' % (c['rid'], c['reclaimed_after']) for c in s['crashed_claims']),
                           s['in_flight_peak'], s['in_flight_overshoot'], d - 1))

    out += ['', '## Experiment 3: finalize serialization (100 concurrent finalizes)', '',
            row('Major', 'Variant', 'Contents', 'Created', 'Reused', 'Max active per revision', 'Tries max', 'Slowest (s)', 'Tries histogram'),
            row(*['---'] * 9)]
    for m in majors:
        for v in ('guarded-c1', 'guarded-c3', 'control-c1'):
            s = load(EV / m / ('exp3-%s.json' % v))['summary']
            (EV / m / ('exp3-%s.summary.json' % v)).write_text(json.dumps(s, indent=1))
            out.append(row(s['version'], s['variant'], s['contents'], s['created'], s['reused'],
                           s['sampled_max_active_per_revision'], s['tries_max'], s['seconds_max'],
                           ' '.join('%s:%s' % kv for kv in s['tries_histogram'].items())))

    out += ['', '## Experiment 4: majority writes across a primary failure (10 rounds each)', '',
            row('Major', 'Fault', 'Acknowledged', 'Missing', 'Errored (present anyway)', 'Error types',
                'Write gap per round (s)', 'Max gap (s)'),
            row(*['---'] * 8)]
    for m in majors:
        for mode in ('kill', 'stepdown'):
            d = load(EV / m / ('exp4-%s.json' % mode))
            s = d['summary']
            (EV / m / ('exp4-%s.summary.json' % mode)).write_text(json.dumps(dict(summary=s, faults=d['faults']), indent=1))
            out.append(row(s['version'], mode, s['acked'], s['acked_missing'],
                           '%s (%s)' % (s['errored'], s['errored_but_present']), ', '.join(s['error_types']) or '-',
                           ' '.join(str(f['max_ack_gap_seconds']) for f in d['faults']), s['max_ack_gap_seconds']))
    (EV / 'RESULTS.md').write_text('\n'.join(out) + '\n')

    manifest = []
    for p in sorted(EV.rglob('*')):
        if p.is_file() and not p.name.endswith(KEEP):
            manifest.append('%s  %d  %s' % (hashlib.sha256(p.read_bytes()).hexdigest(), p.stat().st_size, p.relative_to(HERE)))
    (HERE / 'EXCLUDED.sha256').write_text('\n'.join(manifest) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
